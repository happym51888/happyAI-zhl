const heightByKind: Record<Card['kind'], number> = {
	hero: 330,
	photo: 300,
	link: 200,
	list: 220,
	note: 150,
	quote: 190,
	timeline: 300,
	tags: 210,
	work: 300,
	evolution: 280,
	terminal: 290,
	project: 340,
};

export function estimateHeight(card: Card): number {
	if (card.kind === 'project' && card.href) return 440;
	return heightByKind[card.kind] ?? 200;
}

